-- AI usage quota table for authenticated users.
-- This is a deployment-ready schema for Supabase-backed AI usage tracking.
-- The current Python backend stores usage in SQLite for a zero-cost local setup.
BEGIN;

CREATE TABLE IF NOT EXISTS public.ai_usage_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    session_id text,
    conversation_id text,
    model text NOT NULL DEFAULT 'gemini-flash-lite-latest',
    created_at timestamptz NOT NULL DEFAULT now(),
    created_day date NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')::date,
    minute_bucket timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.ai_usage_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view own AI usage" ON public.ai_usage_events;
CREATE POLICY "Users can view own AI usage"
ON public.ai_usage_events
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert own AI usage" ON public.ai_usage_events;
CREATE POLICY "Users can insert own AI usage"
ON public.ai_usage_events
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users cannot modify another user's AI usage" ON public.ai_usage_events;
CREATE POLICY "Users cannot modify another user's AI usage"
ON public.ai_usage_events
FOR UPDATE
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users cannot delete another user's AI usage" ON public.ai_usage_events;
CREATE POLICY "Users cannot delete another user's AI usage"
ON public.ai_usage_events
FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS ai_usage_events_user_day_idx
ON public.ai_usage_events (user_id, created_day);

CREATE INDEX IF NOT EXISTS ai_usage_events_user_minute_idx
ON public.ai_usage_events (user_id, minute_bucket);

CREATE INDEX IF NOT EXISTS ai_usage_events_day_idx
ON public.ai_usage_events (created_day);

COMMIT;
